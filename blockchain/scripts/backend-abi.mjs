import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import process from "node:process";
const source = new URL(
  "../artifacts/CertificateRegistry.v1.abi.json",
  import.meta.url,
);
const target = new URL(
  "../../supabase/functions/_shared/blockchain/data/registry_abi.ts",
  import.meta.url,
);
const build = JSON.parse(
  readFileSync(new URL("../artifacts/build-reference.json", import.meta.url)),
);
const content =
  `// deno-fmt-ignore-file\n// Generated by blockchain/scripts/backend-abi.mjs; do not edit.\nexport const registryAbi = ${
    JSON.stringify(JSON.parse(readFileSync(source)), null, 2)
  } as const;\nexport const registryRuntimeHash = ${
    JSON.stringify(build.runtimeCodeHash)
  } as const;\n`;
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== content) {
    throw new Error("Backend ABI drift");
  }
} else {
  mkdirSync(new URL(".", target), { recursive: true });
  writeFileSync(target, content);
}
